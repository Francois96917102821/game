create or replace function public.guild_hall_claim(p_service text, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_guild public.guilds%rowtype;
  v_next timestamptz;
  v_free boolean := false;
  v_luck integer := 0;
  v_response jsonb;
  v_receipt public.guild_request_receipts%rowtype;
  v_alchemy integer;
begin
  if p_service not in ('healer', 'alchemist', 'statue', 'scribe') or p_request_id is null then
    raise exception 'Служба ратуши недоступна.';
  end if;
  select guild_id into v_guild_id from public.guild_members where user_id = v_user_id;
  if v_guild_id is null then raise exception 'Ты не состоишь в гильдии.'; end if;
  perform 1 from public.guilds where id = v_guild_id for update;
  select * into v_receipt from public.guild_request_receipts
    where guild_id = v_guild_id and user_id = v_user_id and request_id = p_request_id;
  if found then return v_receipt.response; end if;
  select * into v_guild from public.guilds where id = v_guild_id;
  if coalesce((v_guild.buildings ->> p_service)::integer, 0) < 1 then
    raise exception 'Эта служба ещё не построена.';
  end if;
  select next_available_at into v_next from public.guild_service_cooldowns
    where guild_id = v_guild_id and user_id = v_user_id and service = p_service for update;
  if v_next is not null and v_next > now() then raise exception 'Эта служба ещё восстанавливается.'; end if;
  if p_service = 'healer' then v_free := coalesce((v_guild.buildings ->> 'healer_free')::boolean, false); end if;
  if p_service = 'statue' then
    v_free := coalesce((v_guild.buildings ->> 'statue_free')::boolean, false);
    v_luck := case when coalesce((v_guild.buildings ->> 'statue_free')::boolean, false) then 15 else 10 end;
  end if;
  if p_service = 'scribe' then raise exception 'Книги и награды летописца пока отсутствуют в игре.'; end if;
  if not v_free and v_guild.reputation < 1 then raise exception 'В гильдейской казне не хватает 1 репутации.'; end if;
  update public.guilds set reputation = reputation - case when v_free then 0 else 1 end where id = v_guild_id;
  insert into public.guild_service_cooldowns (guild_id, user_id, service, next_available_at)
    values (v_guild_id, v_user_id, p_service, now() + interval '20 hours')
    on conflict (guild_id, user_id, service) do update set next_available_at = excluded.next_available_at;
  v_alchemy := greatest(0, coalesce((v_guild.buildings ->> 'alchemist_bonus')::integer, 0));
  v_response := jsonb_build_object('ok', true, 'service', p_service, 'free', v_free,
    'health_potions', case when p_service = 'alchemist' then 10 + v_alchemy * 10 else 0 end,
    'regeneration_potions', case when p_service = 'alchemist' then 1 + v_alchemy else 0 end,
    'guild_mask', case when p_service = 'alchemist' then 1 else 0 end,
    'luck', v_luck, 'luck_expires_at', case when v_luck > 0 then now() + interval '10 minutes' else null end,
    'heal_all_injuries', p_service = 'healer',
    'guild', (select public.guild_state() -> 'guild'));
  insert into public.guild_request_receipts (guild_id, user_id, request_id, action, payload, response)
    values (v_guild_id, v_user_id, p_request_id, 'hall_claim', jsonb_build_object('service', p_service), v_response);
  return v_response;
end;
$$;

