create or replace function public.guild_chat_send(p_body text, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_nickname text;
  v_body text := btrim(p_body);
  v_message_id bigint;
  v_reply text;
begin
  if v_user_id is null or p_request_id is null or length(v_body) not between 1 and 500 then
    raise exception 'Сообщение пустое или слишком длинное.';
  end if;
  select guild_id, nickname into v_guild_id, v_nickname from public.guild_members where user_id = v_user_id;
  if v_guild_id is null then raise exception 'Ты не состоишь в гильдии.'; end if;
  if exists (select 1 from public.guild_chat_messages where guild_id = v_guild_id and user_id = v_user_id
    and created_at > now() - interval '2 seconds') then
    raise exception 'Подожди немного перед следующим сообщением.';
  end if;
  insert into public.guild_chat_messages (guild_id, user_id, nickname, kind, body, request_id)
    values (v_guild_id, v_user_id, v_nickname, 'member', v_body, p_request_id)
    on conflict (guild_id, user_id, request_id) do nothing returning id into v_message_id;
  if v_message_id is null then return public.guild_state(); end if;
  if lower(v_body) in ('смотритель', '/смотритель', '!смотритель', 'помощь смотрителя') then
    v_reply := 'Я храню летопись и состояние гильдии. Для построек и состава обратись к главе или офицеру; открытые службы появятся в ратуше.';
    insert into public.guild_chat_messages (guild_id, user_id, nickname, kind, body)
      values (v_guild_id, null, 'Воплощение смотрителя', 'keeper', v_reply);
  end if;
  return public.guild_state();
end;
$$;

create or replace function public.guild_member_manage(p_member_id uuid, p_action text)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_actor_rank text;
  v_target_rank text;
begin
  select guild_id, rank into v_guild_id, v_actor_rank from public.guild_members
    where user_id = v_user_id for update;
  if v_guild_id is null or v_actor_rank <> 'leader' or p_member_id is null then
    raise exception 'Управлять составом может только глава гильдии.';
  end if;
  select rank into v_target_rank from public.guild_members
    where guild_id = v_guild_id and user_id = p_member_id for update;
  if v_target_rank is null or v_target_rank = 'leader' then raise exception 'Участник не найден.'; end if;
  if p_action = 'promote' then
    update public.guild_members set rank = 'officer' where guild_id = v_guild_id and user_id = p_member_id;
  elsif p_action = 'demote' then
    update public.guild_members set rank = 'member' where guild_id = v_guild_id and user_id = p_member_id;
  elsif p_action = 'kick' then
    delete from public.guild_members where guild_id = v_guild_id and user_id = p_member_id;
  else raise exception 'Неизвестное действие с участником.'; end if;
  return public.guild_state();
end;
$$;

