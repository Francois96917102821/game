create or replace function public.guild_treasury_move(
  p_kind text, p_amount bigint, p_direction text, p_wallet_balance bigint, p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_rank text;
  v_guild public.guilds%rowtype;
  v_receipt public.guild_request_receipts%rowtype;
  v_response jsonb;
  v_net bigint;
  v_fee bigint;
begin
  select guild_id, rank into v_guild_id, v_rank from public.guild_members where user_id = (select auth.uid());
  if v_guild_id is null then raise exception 'Ты не состоишь в гильдии.'; end if;
  perform 1 from public.guilds where id = v_guild_id for update;
  select * into v_receipt from public.guild_request_receipts where guild_id = v_guild_id
    and user_id = v_user_id and request_id = p_request_id;
  if found then return v_receipt.response; end if;
  select * into v_guild from public.guilds where id = v_guild_id;
  if coalesce((v_guild.buildings ->> 'treasury')::integer, 0) = 0 or
    p_kind not in ('gold', 'essence') or p_direction not in ('deposit', 'withdraw') or
    p_amount not between 1 and 1000000000 then raise exception 'Казначейская операция недоступна.'; end if;
  if p_direction = 'deposit' then
    if p_wallet_balance < p_amount then raise exception 'Личный баланс недостаточен.'; end if;
    v_fee := case p_kind when 'gold' then ceil(p_amount * 0.1)::bigint else ceil(p_amount * 0.05)::bigint end;
    if coalesce((v_guild.buildings ->> 'treasurer')::integer, 0) > 0 then
      v_net := p_amount - v_fee + floor(v_fee / 2.0)::bigint;
    else v_net := p_amount - v_fee; end if;
    if p_kind = 'gold' then update public.guilds set treasury_gold = least(1000000000, treasury_gold + v_net) where id = v_guild_id;
    else update public.guilds set treasury_essence = least(1000000000, treasury_essence + v_net) where id = v_guild_id; end if;
  else
    if v_rank not in ('leader', 'officer') or
      (v_rank = 'officer' and v_guild.settings ->> 'withdrawal' <> 'officer') then
      raise exception 'Настройки гильдии запрещают изъятие.';
    end if;
    if p_kind = 'gold' then
      if v_guild.treasury_gold < p_amount then raise exception 'В казне недостаточно золота.'; end if;
      update public.guilds set treasury_gold = treasury_gold - p_amount where id = v_guild_id;
    else
      if v_guild.treasury_essence < p_amount then raise exception 'В казне недостаточно осколков.'; end if;
      update public.guilds set treasury_essence = treasury_essence - p_amount where id = v_guild_id;
    end if;
    v_net := p_amount; v_fee := 0;
  end if;
  v_response := jsonb_build_object('ok', true, 'kind', p_kind, 'direction', p_direction,
    'amount', p_amount, 'net', v_net, 'fee', v_fee, 'guild', (select public.guild_state() -> 'guild'));
  insert into public.guild_request_receipts (guild_id, user_id, request_id, action, payload, response)
    values (v_guild_id, v_user_id, p_request_id, 'treasury',
      jsonb_build_object('kind', p_kind, 'amount', p_amount, 'direction', p_direction), v_response);
  return v_response;
end;
$$;

create or replace function public.guild_storage_take(p_item_id bigint, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_rank text;
  v_withdrawal text;
  v_item jsonb;
  v_receipt public.guild_request_receipts%rowtype;
  v_response jsonb;
begin
  if p_item_id is null or p_request_id is null then raise exception 'Изъятие со склада не подтверждено.'; end if;
  select member.guild_id, member.rank, guild.settings ->> 'withdrawal'
    into v_guild_id, v_rank, v_withdrawal
    from public.guild_members member join public.guilds guild on guild.id = member.guild_id
    where member.user_id = v_user_id;
  if v_guild_id is null or
    (v_rank <> 'leader' and (v_withdrawal <> 'officer' or v_rank <> 'officer')) then
    raise exception 'Настройки гильдии запрещают изъятие со склада.';
  end if;
  perform 1 from public.guilds where id = v_guild_id for update;
