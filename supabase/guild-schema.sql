create or replace function public.guild_contribute(
  p_kind text, p_amount bigint, p_balance bigint, p_item jsonb, p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_guild public.guilds%rowtype;
  v_net bigint;
  v_response jsonb;
  v_existing public.guild_request_receipts%rowtype;
  v_receipt jsonb;
  v_item_count integer;
  v_warehouse integer;
  v_resource text;
  v_id bigint;
begin
  if v_user_id is null or p_request_id is null then raise exception 'Вклад не подтверждён.'; end if;
  select guild_id into v_guild_id from public.guild_members where user_id = v_user_id;
  if v_guild_id is null then raise exception 'Ты не состоишь в гильдии.'; end if;
  perform 1 from public.guilds where id = v_guild_id for update;
  select * into v_existing from public.guild_request_receipts
    where guild_id = v_guild_id and user_id = v_user_id and request_id = p_request_id;
  if found then return v_existing.response; end if;
  if p_amount is null or p_amount not between 1 and 1000000000 then raise exception 'Количество вклада недопустимо.'; end if;
  select * into v_guild from public.guilds where id = v_guild_id;
  if p_kind in ('gold', 'essence') then
    if coalesce((v_guild.buildings ->> 'treasury')::integer, 0) = 0 then
      raise exception 'Сначала построй казну гильдии.';
    end if;
    if p_balance is null or p_balance < p_amount then raise exception 'В личном запасе недостаточно средств.'; end if;
    v_net := case p_kind when 'gold' then floor(p_amount * 0.9)::bigint else floor(p_amount * 0.95)::bigint end;
    if p_kind = 'gold' then
      update public.guilds set treasury_gold = least(1000000000, treasury_gold + v_net) where id = v_guild_id;
    else
      update public.guilds set treasury_essence = least(1000000000, treasury_essence + v_net) where id = v_guild_id;
    end if;
  elsif p_kind = 'elite_trophy' then
    if p_balance is null or p_balance < p_amount then raise exception 'Недостаточно элитных трофеев.'; end if;
    update public.guilds set reputation = least(1000000000, reputation + p_amount) where id = v_guild_id;
    v_net := p_amount;
  elsif p_kind in ('boards', 'blocks', 'cloth', 'ingots', 'knowledge_roots', 'heart_fragments') then
    if p_balance is null or p_balance < p_amount then raise exception 'Недостаточно материалов.'; end if;
    update public.guilds set resources = jsonb_set(resources, array[p_kind],
      to_jsonb(least(1000000000, coalesce((resources ->> p_kind)::bigint, 0) + p_amount)), true)
      where id = v_guild_id;
    v_net := p_amount;
  elsif p_kind = 'item' then
    if jsonb_typeof(p_item) <> 'object' or
      coalesce(p_item ->> 'id', '') !~ '^gear-[0-9]{1,10}$' or
      p_item ->> 'type' not in ('weapon', 'armor') or
      length(coalesce(p_item ->> 'name', '')) not between 1 and 60 or
      coalesce(p_item ->> 'bonus', '') !~ '^[1-9]$' then
      raise exception 'Предмет не прошёл проверку склада.';
    end if;
    v_warehouse := coalesce((v_guild.buildings ->> 'warehouse')::integer, 0);
    if v_warehouse < 1 then raise exception 'Сначала построй склад гильдии.'; end if;
    select count(*) into v_item_count from public.guild_storage_items where guild_id = v_guild_id;
    if v_item_count >= 90 + 10 * v_warehouse then raise exception 'Склад гильдии заполнен.'; end if;
    insert into public.guild_storage_items (guild_id, deposited_by, item)
      values (v_guild_id, v_user_id, p_item) returning id into v_id;
    v_net := 1;
  else raise exception 'Этот вклад нельзя внести.'; end if;
  v_response := jsonb_build_object('ok', true, 'kind', p_kind, 'amount', p_amount,
    'net', v_net, 'fee', case p_kind when 'gold' then p_amount - v_net when 'essence' then p_amount - v_net else 0 end,
    'item_id', v_id, 'guild', (select public.guild_state() -> 'guild'));
  insert into public.guild_request_receipts (guild_id, user_id, request_id, action, payload, response)
