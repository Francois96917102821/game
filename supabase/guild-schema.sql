create table if not exists public.guilds (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(name) between 3 and 32),
  leader_id uuid not null references auth.users (id) on delete cascade,
  guild_level integer not null default 1 check (guild_level between 1 and 100),
  reputation bigint not null default 0 check (reputation between 0 and 1000000000),
  treasury_gold bigint not null default 0 check (treasury_gold between 0 and 1000000000),
  treasury_essence bigint not null default 0 check (treasury_essence between 0 and 1000000000),
  resources jsonb not null default '{"boards":0,"blocks":0,"cloth":0,"ingots":0,"knowledge_roots":0,"heart_fragments":0}'::jsonb
    check (jsonb_typeof(resources) = 'object'),
  buildings jsonb not null default '{}'::jsonb check (jsonb_typeof(buildings) = 'object'),
  settings jsonb not null default '{"withdrawal":"officer"}'::jsonb check (jsonb_typeof(settings) = 'object'),
  created_at timestamptz not null default now()
);

create table if not exists public.guild_members (
  guild_id uuid not null references public.guilds (id) on delete cascade,
  user_id uuid not null unique references auth.users (id) on delete cascade,
  nickname text not null check (length(nickname) between 1 and 24),
  rank text not null default 'member' check (rank in ('leader', 'officer', 'member')),
  joined_at timestamptz not null default now(),
  primary key (guild_id, user_id)
);
create index if not exists guild_members_guild_idx on public.guild_members (guild_id, joined_at);

create table if not exists public.guild_invites (
  guild_id uuid primary key references public.guilds (id) on delete cascade,
  code text not null unique check (code ~ '^[A-F0-9]{8}$'),
  created_by uuid not null references auth.users (id) on delete cascade,
  expires_at timestamptz not null
);

create table if not exists public.guild_chat_messages (
  id bigint generated by default as identity primary key,
  guild_id uuid not null references public.guilds (id) on delete cascade,
  user_id uuid references auth.users (id) on delete set null,
  nickname text not null check (length(nickname) between 1 and 32),
  kind text not null check (kind in ('member', 'keeper', 'system')),
  body text not null check (length(body) between 1 and 500),
  request_id uuid,
  created_at timestamptz not null default now(),
  unique (guild_id, user_id, request_id)
);
create index if not exists guild_chat_recent_idx on public.guild_chat_messages (guild_id, id desc);

create table if not exists public.guild_storage_items (
  id bigint generated by default as identity primary key,
  guild_id uuid not null references public.guilds (id) on delete cascade,
  deposited_by uuid not null references auth.users (id) on delete cascade,
  item jsonb not null check (
    jsonb_typeof(item) = 'object' and
    item ?& array['id', 'type', 'name', 'bonus'] and
    item ->> 'id' ~ '^gear-[0-9]{1,10}$' and
    item ->> 'type' in ('weapon', 'armor') and
    length(item ->> 'name') between 1 and 60 and
    coalesce((item ->> 'bonus')::integer, 0) between 1 and 10
  ),
  created_at timestamptz not null default now()
);
create index if not exists guild_storage_items_idx on public.guild_storage_items (guild_id, id);

create table if not exists public.guild_service_cooldowns (
  guild_id uuid not null references public.guilds (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  service text not null check (service in ('healer', 'alchemist', 'statue', 'scribe')),
  next_available_at timestamptz not null,
  primary key (guild_id, user_id, service)
);

create table if not exists public.guild_request_receipts (
  guild_id uuid not null references public.guilds (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  request_id uuid not null,
  action text not null,
  payload jsonb not null,
  response jsonb not null,
  created_at timestamptz not null default now(),
  primary key (guild_id, user_id, request_id)
);

