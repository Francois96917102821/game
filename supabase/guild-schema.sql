create or replace function public.guild_build(p_building text, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_rank text;
  v_guild public.guilds%rowtype;
  v_receipt public.guild_request_receipts%rowtype;
  v_rep bigint := 0;
  v_gold bigint := 0;
  v_level integer;
  v_cost jsonb := '{}'::jsonb;
  v_key text;
  v_amount integer;
  v_resources jsonb;
  v_response jsonb;
begin
  select guild_id, rank into v_guild_id, v_rank from public.guild_members where user_id = v_user_id for update;
  if v_guild_id is null or v_rank not in ('leader', 'officer') then raise exception 'Строить может глава или офицер.'; end if;
  if p_request_id is null then raise exception 'Строительство не подтверждено.'; end if;
  perform 1 from public.guilds where id = v_guild_id for update;
  select * into v_receipt from public.guild_request_receipts
    where guild_id = v_guild_id and user_id = v_user_id and request_id = p_request_id;
  if found then return v_receipt.response; end if;
  select * into v_guild from public.guilds where id = v_guild_id;
  v_level := coalesce((v_guild.buildings ->> p_building)::integer, 0);

  if p_building <> 'castle' and coalesce((v_guild.buildings ->> 'castle')::integer, 0) < 1 then
    raise exception 'Сначала построй замок гильдии.';
  end if;
  case p_building
    when 'castle' then v_rep := 1000; v_cost := '{"boards":50,"blocks":50,"cloth":25,"ingots":25}'::jsonb;
    when 'treasury' then if v_level > 0 then raise exception 'Казна уже построена.'; end if;
      v_cost := '{"boards":20,"blocks":20,"ingots":20}'::jsonb;
    when 'book_storage' then if v_level > 0 then raise exception 'Книгохранилище уже построено.'; end if;
      v_cost := '{"boards":20,"blocks":20,"cloth":20}'::jsonb;
    when 'warehouse' then if v_level >= 100 then raise exception 'Достигнут предел склада.'; end if;
      v_cost := '{"boards":10,"blocks":10,"cloth":5,"ingots":5}'::jsonb;
    when 'treasurer' then if v_level > 0 then raise exception 'Казначей уже назначен.'; end if;
      v_rep := 500; v_gold := 250000;
    when 'healer' then if v_level > 0 then raise exception 'Лекарь уже построен.'; end if;
      v_rep := 300;
    when 'alchemist' then if v_level > 0 then raise exception 'Алхимик уже построен.'; end if;
      v_rep := 200;
    when 'statue' then if v_level > 0 then raise exception 'Статуя уже построена.'; end if;
      v_rep := 50;
    when 'scribe' then if v_level > 0 then raise exception 'Летописец уже построен.'; end if;
      v_rep := 500; v_cost := '{"knowledge_roots":25}'::jsonb;
    when 'craft' then if v_level > 0 then raise exception 'Ремесленная комната уже построена.'; end if;
      v_rep := 100; v_cost := '{"heart_fragments":1}'::jsonb;
    when 'forge' then if v_level > 0 then raise exception 'Кузница уже построена.'; end if;
      v_rep := 400; v_cost := '{"heart_fragments":1}'::jsonb;
    else raise exception 'Неизвестная постройка.'; end case;
  if v_guild.reputation < v_rep or v_guild.treasury_gold < v_gold then
    raise exception 'В казне недостаточно золота или репутации.';
  end if;
  v_resources := v_guild.resources;
  for v_key in select jsonb_object_keys(v_cost) loop
    v_amount := (v_cost ->> v_key)::integer;
    if coalesce((v_guild.resources ->> v_key)::integer, 0) < v_amount then
      raise exception 'В гильдейском складе не хватает ресурсов.';
    end if;
    v_resources := jsonb_set(v_resources, array[v_key],
      to_jsonb(coalesce((v_resources ->> v_key)::integer, 0) - v_amount), true);
  end loop;
  update public.guilds set reputation = reputation - v_rep, treasury_gold = treasury_gold - v_gold,
    buildings = jsonb_set(buildings, array[p_building],
      to_jsonb(coalesce((buildings ->> p_building)::integer, 0) + 1), true),
    resources = v_resources
    where id = v_guild_id;
  v_response := jsonb_build_object('ok', true, 'building', p_building, 'guild', (select public.guild_state() -> 'guild'));
  insert into public.guild_request_receipts (guild_id, user_id, request_id, action, payload, response)
    values (v_guild_id, v_user_id, p_request_id, 'build', jsonb_build_object('building', p_building), v_response);
  return v_response;
end;
$$;

