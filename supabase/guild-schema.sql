create or replace function public.my_guild_ids()
returns setof uuid
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select guild_id from public.guild_members where user_id = (select auth.uid())
$$;

revoke all on function public.my_guild_ids() from public, anon;
grant execute on function public.my_guild_ids() to authenticated;

drop policy if exists "Guild members can read guilds" on public.guilds;
create policy "Guild members can read guilds" on public.guilds
  for select to authenticated using (id in (select public.my_guild_ids()));
drop policy if exists "Guild members can read roster" on public.guild_members;
create policy "Guild members can read roster" on public.guild_members
  for select to authenticated using (guild_id in (select public.my_guild_ids()));
drop policy if exists "Guild members can read chat" on public.guild_chat_messages;
create policy "Guild members can read chat" on public.guild_chat_messages
  for select to authenticated using (guild_id in (select public.my_guild_ids()));
drop policy if exists "Guild members can read storage" on public.guild_storage_items;
create policy "Guild members can read storage" on public.guild_storage_items
  for select to authenticated using (guild_id in (select public.my_guild_ids()));
drop policy if exists "Guild members can read own cooldowns" on public.guild_service_cooldowns;
create policy "Guild members can read own cooldowns" on public.guild_service_cooldowns
  for select to authenticated using (
    user_id = (select auth.uid()) and guild_id in (select public.my_guild_ids())
  );
drop policy if exists "Guild members can read own receipts" on public.guild_request_receipts;
create policy "Guild members can read own receipts" on public.guild_request_receipts
  for select to authenticated using (
    user_id = (select auth.uid()) and guild_id in (select public.my_guild_ids())
  );
grant select on public.guilds, public.guild_members, public.guild_chat_messages,
  public.guild_storage_items, public.guild_service_cooldowns, public.guild_request_receipts
  to authenticated;
revoke insert, update, delete on public.guilds, public.guild_members, public.guild_invites,
  public.guild_chat_messages, public.guild_storage_items, public.guild_service_cooldowns,
  public.guild_request_receipts from public, anon, authenticated;

create or replace function public.guild_state()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_guild public.guilds%rowtype;
  v_members jsonb;
  v_messages jsonb;
  v_items jsonb;
  v_role text;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  select guild_id into v_guild_id from public.guild_members where user_id = v_user_id;
  if v_guild_id is null then return jsonb_build_object('guild', null); end if;
  select * into v_guild from public.guilds where id = v_guild_id;
  select rank into v_role from public.guild_members where guild_id = v_guild_id and user_id = v_user_id;
  select coalesce(jsonb_agg(jsonb_build_object(
    'user_id', member.user_id, 'nickname', member.nickname, 'rank', member.rank,
    'joined_at', member.joined_at
  ) order by case member.rank when 'leader' then 0 when 'officer' then 1 else 2 end, member.joined_at), '[]'::jsonb)
  into v_members from public.guild_members member where member.guild_id = v_guild_id;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', recent.id, 'user_id', recent.user_id, 'nickname', recent.nickname,
    'kind', recent.kind, 'body', recent.body, 'created_at', recent.created_at
  ) order by recent.id), '[]'::jsonb)
  into v_messages from (
    select * from public.guild_chat_messages where guild_id = v_guild_id order by id desc limit 50
  ) recent;
  select coalesce(jsonb_agg(jsonb_build_object('id', item.id, 'item', item.item, 'deposited_by', item.deposited_by)
    order by item.id), '[]'::jsonb)
  into v_items from public.guild_storage_items item where item.guild_id = v_guild_id;
  return jsonb_build_object(
    'guild', jsonb_build_object(
      'id', v_guild.id, 'name', v_guild.name, 'leader_id', v_guild.leader_id,
      'guild_level', v_guild.guild_level, 'reputation', v_guild.reputation,
      'treasury_gold', v_guild.treasury_gold, 'treasury_essence', v_guild.treasury_essence,
      'resources', v_guild.resources, 'buildings', v_guild.buildings,
      'settings', v_guild.settings, 'role', v_role, 'created_at', v_guild.created_at,
      'members', v_members, 'messages', v_messages, 'items', v_items,
      'invitation', (select jsonb_build_object('code', invite.code, 'expires_at', invite.expires_at)
        from public.guild_invites invite where invite.guild_id = v_guild_id and invite.created_by = v_user_id
          and invite.expires_at > now()),
      'cooldowns', (select coalesce(jsonb_object_agg(service, next_available_at), '{}'::jsonb)
        from public.guild_service_cooldowns where guild_id = v_guild_id and user_id = v_user_id)
    )
  );
end;
$$;

create or replace function public.guild_create(p_name text, p_nickname text)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_name text := btrim(p_name);
  v_nickname text := btrim(p_nickname);
begin
  if v_user_id is null or v_name is null or length(v_name) not between 3 and 32 or
    v_nickname is null or length(v_nickname) not between 1 and 24 then
    raise exception 'Проверь название гильдии и свой ник.';
  end if;
  if exists (select 1 from public.guild_members where user_id = v_user_id) then
    raise exception 'Ты уже состоишь в гильдии.';
  end if;
  insert into public.guilds (name, leader_id) values (v_name, v_user_id) returning id into v_guild_id;
  insert into public.guild_members (guild_id, user_id, nickname, rank)
    values (v_guild_id, v_user_id, v_nickname, 'leader');
  insert into public.guild_chat_messages (guild_id, user_id, nickname, kind, body)
    values (v_guild_id, null, 'Воплощение смотрителя', 'keeper',
      'Добро пожаловать. Я буду хранить хронику, сообщения и состояние гильдейского холла.');
  return public.guild_state();
end;
$$;

create or replace function public.guild_create_invite()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_code text;
begin
  select guild_id into v_guild_id from public.guild_members
    where user_id = v_user_id and rank in ('leader', 'officer');
  if v_guild_id is null then raise exception 'Код приглашения может выпустить только глава или офицер.'; end if;
  v_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
  insert into public.guild_invites (guild_id, code, created_by, expires_at)
    values (v_guild_id, v_code, v_user_id, now() + interval '7 days')
    on conflict (guild_id) do update set code = excluded.code,
      created_by = excluded.created_by, expires_at = excluded.expires_at;
  return public.guild_state();
end;
$$;

create or replace function public.guild_join(p_code text, p_nickname text)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_guild_id uuid;
  v_nickname text := btrim(p_nickname);
  v_count integer;
begin
  if v_user_id is null or v_nickname is null or length(v_nickname) not between 1 and 24 then
    raise exception 'Ник должен содержать 1–24 символа.';
  end if;
  if exists (select 1 from public.guild_members where user_id = v_user_id) then
    raise exception 'Ты уже состоишь в гильдии.';
  end if;
  select guild_id into v_guild_id from public.guild_invites
    where code = upper(btrim(p_code)) and expires_at > now();
  if v_guild_id is null then raise exception 'Код приглашения не найден или истёк.'; end if;
  perform 1 from public.guilds where id = v_guild_id for update;
  select count(*) into v_count from public.guild_members where guild_id = v_guild_id;
  if v_count >= 100 then raise exception 'В гильдии уже 100 участников.'; end if;
  insert into public.guild_members (guild_id, user_id, nickname) values (v_guild_id, v_user_id, v_nickname);
  insert into public.guild_chat_messages (guild_id, user_id, nickname, kind, body)
    values (v_guild_id, null, 'Воплощение смотрителя', 'keeper',
      v_nickname || ' присоединился к гильдии.');
  return public.guild_state();
end;
$$;

