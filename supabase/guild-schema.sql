    if v_receipt.action <> 'storage_take' or v_receipt.payload <> jsonb_build_object('item_id', p_item_id) then
      raise exception 'Квитанция уже использована для другого действия.';
    end if;
    return v_receipt.response;
  end if;
  delete from public.guild_storage_items where id = p_item_id and guild_id = v_guild_id
    returning item into v_item;
  if v_item is null then raise exception 'Предмет на складе не найден.'; end if;
  v_response := jsonb_build_object('item', v_item, 'guild', (select public.guild_state() -> 'guild'));
  insert into public.guild_request_receipts (guild_id, user_id, request_id, action, payload, response)
    values (v_guild_id, v_user_id, p_request_id, 'storage_take',
      jsonb_build_object('item_id', p_item_id), v_response);
