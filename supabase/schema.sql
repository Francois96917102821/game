-- Player groups expose only small member summaries. Game saves remain private
-- to their owner and are never joined to group data.
create table if not exists public.player_groups (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.player_group_members (
  group_id uuid not null references public.player_groups (id) on delete cascade,
  user_id uuid not null unique references auth.users (id) on delete cascade,
  nickname text not null check (length(nickname) between 1 and 24),
  level integer not null check (level between 1 and 10000),
  in_dungeon boolean not null default false,
  heartbeat_at timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);

create table if not exists public.player_group_invites (
  group_id uuid primary key references public.player_groups (id) on delete cascade,
  code text not null unique check (code ~ '^[A-F0-9]{8}$'),
  created_by uuid not null references auth.users (id) on delete cascade,
  expires_at timestamptz not null,
  used_at timestamptz
);

create table if not exists public.player_group_inbox (
  id bigint generated by default as identity primary key,
  group_id uuid not null references public.player_groups (id) on delete cascade,
  recipient_id uuid not null references auth.users (id) on delete cascade,
  sender_id uuid references auth.users (id) on delete cascade,
  request_id uuid,
  kind text not null check (kind in ('gold', 'essence', 'hint_secret', 'hint_rare')),
  amount integer not null default 0 check (amount between 0 and 100000),
  floor integer not null default 0 check (floor between 0 and 1000000),
  created_at timestamptz not null default now(),
  check ((sender_id is null) = (request_id is null)),
  unique (sender_id, request_id)
);

create table if not exists public.player_group_reward_receipts (
  group_id uuid not null references public.player_groups (id) on delete cascade,
  sender_id uuid not null references auth.users (id) on delete cascade,
  request_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (sender_id, request_id)
);

create index if not exists player_group_members_group_idx
  on public.player_group_members (group_id, joined_at);
create index if not exists player_group_inbox_recipient_idx
  on public.player_group_inbox (recipient_id, id);

