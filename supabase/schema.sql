  v_potions := (p_player ->> 'potions')::integer;
  v_attack := (p_player ->> 'attack')::integer;
  v_defense := coalesce((p_player ->> 'defense')::integer, 0);
  v_focus := (p_player ->> 'focus')::integer;
  v_heavy_multiplier := (p_player ->> 'heavy_multiplier')::numeric;
  if v_max_hp not between 1 and 1000000 or v_hp not between 1 and v_max_hp or
    v_potions not between 0 and 100 or v_attack not between 1 and 1000000 or
    v_defense not between 0 and 1000000 or v_focus not between 0 and 3 or
    v_heavy_multiplier not between 1 and 10 then
    raise exception 'Показатели игрока для совместного боя недопустимы.';
  end if;

  select group_id into v_group_id
  from public.player_group_members
  where user_id = v_user_id and in_dungeon and heartbeat_at > now() - interval '75 seconds'
