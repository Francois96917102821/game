create table if not exists public.game_saves (
  user_id uuid primary key references auth.users (id) on delete cascade,
  save_data jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.game_saves enable row level security;

drop policy if exists "Players can read their own game save" on public.game_saves;
create policy "Players can read their own game save"
  on public.game_saves for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Players can create their own game save" on public.game_saves;
create policy "Players can create their own game save"
  on public.game_saves for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Players can update their own game save" on public.game_saves;
create policy "Players can update their own game save"
  on public.game_saves for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create table if not exists public.game_save_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  save_data jsonb not null,
  source text not null default 'предыдущая облачная копия',
  archived_at timestamptz not null default now()
);

grant select, insert, update on public.game_saves to authenticated;
grant select, insert on public.game_save_history to authenticated;

create index if not exists game_save_history_user_archived_idx
  on public.game_save_history (user_id, archived_at desc);

alter table public.game_save_history enable row level security;

drop policy if exists "Players can read their own save history" on public.game_save_history;
create policy "Players can read their own save history"
  on public.game_save_history for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Players can archive their own local save" on public.game_save_history;
create policy "Players can archive their own local save"
  on public.game_save_history for insert to authenticated
  with check ((select auth.uid()) = user_id);

create or replace function public.archive_previous_game_save()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.save_data is distinct from new.save_data then
    insert into public.game_save_history (user_id, save_data, source)
    values (old.user_id, old.save_data, 'предыдущая облачная копия');
  end if;
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists archive_previous_game_save on public.game_saves;
create trigger archive_previous_game_save
  before update on public.game_saves
  for each row execute function public.archive_previous_game_save();
