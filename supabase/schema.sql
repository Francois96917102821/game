create or replace function public.heartbeat_player_group(p_nickname text, p_level integer, p_in_dungeon boolean)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_min_level integer;
  v_max_level integer;
  v_invite jsonb;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы обновить статус группы.'; end if;
  if p_level is null or p_level not between 1 and 10000 then raise exception 'Уровень игрока недопустим.'; end if;
  if p_nickname is null or length(btrim(p_nickname)) not between 1 and 24 then raise exception 'Ник должен содержать от 1 до 24 символов.'; end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id for update;
  if v_group_id is null then return jsonb_build_object('group', null, 'dissolved', false); end if;

  update public.player_group_members
  set nickname = btrim(p_nickname), level = p_level,
      in_dungeon = coalesce(p_in_dungeon, false), heartbeat_at = now()
  where group_id = v_group_id and user_id = v_user_id;

  select min(level), max(level) into v_min_level, v_max_level
  from public.player_group_members where group_id = v_group_id;
  if v_min_level is not null and v_max_level::numeric / v_min_level >= 3 then
    delete from public.player_groups where id = v_group_id;
    return jsonb_build_object('group', null, 'dissolved', true);
  end if;
  select jsonb_build_object('invite_code', code, 'expires_at', expires_at)
  into v_invite
  from public.player_group_invites
  where group_id = v_group_id and created_by = v_user_id
    and used_at is null and expires_at > now();
  return jsonb_build_object(
    'group', public.player_group_state(v_group_id),
    'invite', v_invite,
    'dissolved', false
  );
end;
$$;

