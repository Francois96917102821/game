  if p_nickname is null or length(btrim(p_nickname)) not between 1 and 24 then raise exception 'Ник должен содержать от 1 до 24 символов.'; end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id for update;
  if v_group_id is null then return jsonb_build_object('group', null, 'dissolved', false); end if;

  update public.player_group_members
  set nickname = btrim(p_nickname), level = p_level,
      in_dungeon = coalesce(p_in_dungeon, false), heartbeat_at = now()
  where group_id = v_group_id and user_id = v_user_id;

  select min(level), max(level) into v_min_level, v_max_level
  from public.player_group_members where group_id = v_group_id;
