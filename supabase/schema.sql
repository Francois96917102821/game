create or replace function public.wallet_transfer(
  p_currency text,
  p_recipient_id uuid,
  p_amount bigint,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_payload jsonb;
  v_existing public.wallet_transactions%rowtype;
  v_transaction_id uuid;
  v_account_id uuid;
  v_sender_balance bigint;
  v_recipient_balance bigint;
  v_fee bigint;
  v_net bigint;
  v_fee_basis_points bigint;
  v_result jsonb;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  if p_currency not in ('gold', 'shard') or p_currency is null then
    raise exception 'Неизвестная валюта.';
  end if;
  if p_recipient_id is null or p_recipient_id = v_user_id or p_request_id is null then
    raise exception 'Получатель или ключ перевода недопустим.';
  end if;
  if p_amount is null or p_amount < 100 or p_amount > 1000000000000 then
    raise exception 'Перевод должен быть не менее 100 и не более 1 000 000 000 000.';
  end if;
  if not exists (select 1 from auth.users where id = p_recipient_id) then
    raise exception 'Получатель не найден.';
  end if;

  v_payload := jsonb_build_object(
    'currency', p_currency,
    'recipient_id', p_recipient_id,
    'amount', p_amount
  );

  for v_account_id in
    select account_id
    from unnest(array[v_user_id, p_recipient_id]) as accounts(account_id)
    order by account_id
  loop
    insert into public.wallet_balances (user_id, currency)
    values (v_account_id, p_currency)
    on conflict (user_id, currency) do nothing;
  end loop;

  -- Lock all affected player accounts in a stable order to serialize spends
  -- and avoid deadlocks when two players transfer to each other concurrently.
  perform 1
  from public.wallet_balances
  where currency = p_currency and user_id in (v_user_id, p_recipient_id)
  order by user_id
  for update;

  select * into v_existing
  from public.wallet_transactions
  where actor_id = v_user_id and request_id = p_request_id and kind = 'transfer';
  if found then
    if v_existing.kind <> 'transfer' or v_existing.payload <> v_payload then
      raise exception 'Ключ перевода уже использован с другими параметрами.';
    end if;
    return v_existing.result;
  end if;

  select balance into v_sender_balance
  from public.wallet_balances
  where user_id = v_user_id and currency = p_currency;
  select balance into v_recipient_balance
  from public.wallet_balances
  where user_id = p_recipient_id and currency = p_currency;
  if v_sender_balance < p_amount then
    raise exception 'Недостаточно средств.';
  end if;

  v_fee_basis_points := case p_currency when 'gold' then 1000 else 500 end;
  v_fee := (p_amount * v_fee_basis_points) / 10000;
  v_net := p_amount - v_fee;
  if v_recipient_balance > 1000000000000 - v_net then
    raise exception 'Баланс получателя достиг предела.';
  end if;

  insert into public.wallet_transactions (actor_id, request_id, kind, currency, payload)
  values (v_user_id, p_request_id, 'transfer', p_currency, v_payload)
  returning id into v_transaction_id;

  update public.wallet_balances
  set balance = balance - p_amount, updated_at = now()
  where user_id = v_user_id and currency = p_currency;
  update public.wallet_balances
  set balance = balance + v_net, updated_at = now()
  where user_id = p_recipient_id and currency = p_currency;

  insert into public.wallet_ledger_entries
    (transaction_id, currency, account_type, user_id, amount)
  values
    (v_transaction_id, p_currency, 'player', v_user_id, -p_amount),
    (v_transaction_id, p_currency, 'player', p_recipient_id, v_net),
    (v_transaction_id, p_currency, 'treasury', null, v_fee);

  v_result := jsonb_build_object(
    'transaction_id', v_transaction_id,
    'currency', p_currency,
    'amount', p_amount,
    'fee', v_fee,
    'received', v_net,
    'balance', v_sender_balance - p_amount
  );
  update public.wallet_transactions set result = v_result where id = v_transaction_id;
  return v_result;
end;
$$;

create or replace function public.wallet_claim_funding_receipts()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_receipt public.wallet_funding_receipts%rowtype;
  v_transaction_id uuid;
  v_balance bigint;
  v_claimed jsonb := '[]'::jsonb;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;

  for v_receipt in
    select * from public.wallet_funding_receipts
    where user_id = v_user_id and claimed_transaction_id is null
    order by created_at, id
    for update skip locked
  loop
    insert into public.wallet_balances (user_id, currency)
    values (v_user_id, v_receipt.currency)
    on conflict (user_id, currency) do nothing;

    select balance into v_balance
    from public.wallet_balances
    where user_id = v_user_id and currency = v_receipt.currency
    for update;
    if v_balance > 1000000000000 - v_receipt.amount then
      raise exception 'Баланс достиг предела; серверную награду сохранить не удалось.';
    end if;

    insert into public.wallet_transactions
      (actor_id, request_id, kind, currency, payload)
    values (
      v_user_id,
      v_receipt.id,
      'funding',
      v_receipt.currency,
      jsonb_build_object(
        'receipt_id', v_receipt.id,
        'source_kind', v_receipt.source_kind,
        'currency', v_receipt.currency,
        'amount', v_receipt.amount
      )
    )
    returning id into v_transaction_id;

    update public.wallet_balances
    set balance = balance + v_receipt.amount, updated_at = now()
    where user_id = v_user_id and currency = v_receipt.currency;
    insert into public.wallet_ledger_entries
      (transaction_id, currency, account_type, user_id, amount)
    values
      (v_transaction_id, v_receipt.currency, 'player', v_user_id, v_receipt.amount),
      (v_transaction_id, v_receipt.currency, 'issuer', null, -v_receipt.amount);
    update public.wallet_transactions
    set result = jsonb_build_object(
      'transaction_id', v_transaction_id,
      'receipt_id', v_receipt.id,
      'currency', v_receipt.currency,
      'amount', v_receipt.amount,
      'balance', v_balance + v_receipt.amount
    )
    where id = v_transaction_id;
    update public.wallet_funding_receipts
    set claimed_at = now(), claimed_transaction_id = v_transaction_id
    where id = v_receipt.id;

    v_claimed := v_claimed || jsonb_build_array(jsonb_build_object(
      'receipt_id', v_receipt.id,
      'source_kind', v_receipt.source_kind,
      'currency', v_receipt.currency,
      'amount', v_receipt.amount
    ));
  end loop;

  return jsonb_build_object(
    'claimed_receipts', v_claimed,
    'balances', public.wallet_get_balances()
  );
end;
$$;

-- This ingestion endpoint is exclusively for trusted backend code holding the
-- Supabase service role. Never expose that key to a browser or static client.
create or replace function public.wallet_register_funding_receipt(
  p_user_id uuid,
  p_currency text,
  p_amount bigint,
  p_source_kind text,
  p_source_ref text
)
returns uuid
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_receipt_id uuid;
  v_existing public.wallet_funding_receipts%rowtype;
begin
  if p_user_id is null or p_currency not in ('gold', 'shard') or p_currency is null or
    p_amount is null or p_amount < 1 or p_amount > 1000000000000 or
    p_source_kind is null or p_source_kind !~ '^[a-z][a-z0-9_]{0,31}$' or
    p_source_ref is null or length(p_source_ref) not between 1 and 200 then
    raise exception 'Параметры серверной награды недопустимы.';
  end if;
  if not exists (select 1 from auth.users where id = p_user_id) then
    raise exception 'Получатель награды не найден.';
  end if;

  insert into public.wallet_funding_receipts
    (user_id, currency, amount, source_kind, source_ref)
  values (p_user_id, p_currency, p_amount, p_source_kind, p_source_ref)
  on conflict (source_kind, source_ref) do nothing
  returning id into v_receipt_id;

  if v_receipt_id is null then
    select * into v_existing
    from public.wallet_funding_receipts
    where source_kind = p_source_kind and source_ref = p_source_ref
    for update;
    if v_existing.user_id <> p_user_id or v_existing.currency <> p_currency or
      v_existing.amount <> p_amount then
      raise exception 'Источник награды уже зарегистрирован с другими параметрами.';
    end if;
    return v_existing.id;
  end if;
  return v_receipt_id;
end;
$$;

