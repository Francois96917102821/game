-- Currency that can be transferred between players must never be derived from
-- game_saves: that document is writable by its owner. Only trusted server-side
-- systems may issue funding receipts; authenticated clients can claim receipts
-- issued to their own account.
create table if not exists public.wallet_balances (
  user_id uuid not null,
  currency text not null check (currency in ('gold', 'shard')),
  balance bigint not null default 0 check (balance between 0 and 1000000000000),
  updated_at timestamptz not null default now(),
  primary key (user_id, currency)
);

create table if not exists public.wallet_transactions (
  id uuid primary key default gen_random_uuid(),
  actor_id uuid not null,
  request_id uuid not null,
  kind text not null check (kind in ('transfer', 'funding')),
  currency text not null check (currency in ('gold', 'shard')),
  payload jsonb not null,
  result jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (id, currency)
);

create table if not exists public.wallet_ledger_entries (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null,
  currency text not null check (currency in ('gold', 'shard')),
  account_type text not null check (account_type in ('player', 'issuer', 'treasury')),
  user_id uuid,
  amount bigint not null check (amount <> 0),
  created_at timestamptz not null default now(),
  check (
    (account_type = 'player' and user_id is not null) or
    (account_type in ('issuer', 'treasury') and user_id is null)
  ),
  foreign key (transaction_id, currency)
    references public.wallet_transactions (id, currency) on delete restrict
);

create table if not exists public.wallet_funding_receipts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  currency text not null check (currency in ('gold', 'shard')),
  amount bigint not null check (amount between 1 and 1000000000000),
  source_kind text not null check (source_kind ~ '^[a-z][a-z0-9_]{0,31}$'),
  source_ref text not null check (length(source_ref) between 1 and 200),
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  claimed_transaction_id uuid unique references public.wallet_transactions (id) on delete restrict,
  unique (source_kind, source_ref),
  check ((claimed_at is null) = (claimed_transaction_id is null))
);

create index if not exists wallet_ledger_transaction_idx
  on public.wallet_ledger_entries (transaction_id);
create unique index if not exists wallet_transfer_request_idx
  on public.wallet_transactions (actor_id, request_id)
  where kind = 'transfer';
create index if not exists wallet_ledger_player_idx
  on public.wallet_ledger_entries (user_id, currency, created_at desc)
  where account_type = 'player';
create index if not exists wallet_funding_receipts_unclaimed_idx
  on public.wallet_funding_receipts (user_id, created_at, id)
  where claimed_transaction_id is null;

alter table public.wallet_balances enable row level security;
alter table public.wallet_transactions enable row level security;
alter table public.wallet_ledger_entries enable row level security;
alter table public.wallet_funding_receipts enable row level security;

revoke all on public.wallet_balances, public.wallet_transactions,
  public.wallet_ledger_entries, public.wallet_funding_receipts
  from public, anon, authenticated, service_role;

