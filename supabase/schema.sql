create or replace function public.player_group_state(p_group_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_members jsonb;
begin
  if v_user_id is null or not exists (
    select 1 from public.player_group_members
    where group_id = p_group_id and user_id = v_user_id
  ) then
    raise exception 'Группа недоступна для этого аккаунта.';
  end if;

  select jsonb_agg(
    jsonb_build_object(
      'user_id', member.user_id,
      'nickname', member.nickname,
      'level', member.level,
      'in_dungeon', member.in_dungeon and member.heartbeat_at > now() - interval '75 seconds'
    )
    order by member.joined_at
  )
  into v_members
  from public.player_group_members as member
  where member.group_id = p_group_id;

  return jsonb_build_object('id', p_group_id, 'members', coalesce(v_members, '[]'::jsonb));
end;
$$;

revoke all on function public.player_group_state(uuid) from public, anon, authenticated;

create or replace function public.create_player_group(p_nickname text, p_level integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_code text;
  v_expiration timestamptz := now() + interval '15 minutes';
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы создать группу.'; end if;
  if p_level is null or p_level not between 1 and 10000 then raise exception 'Уровень игрока недопустим.'; end if;
  if p_nickname is null or length(btrim(p_nickname)) not between 1 and 24 then raise exception 'Ник должен содержать от 1 до 24 символов.'; end if;
  if exists (select 1 from public.player_group_members where user_id = v_user_id) then
    raise exception 'Ты уже состоишь в группе.';
  end if;

  insert into public.player_groups default values returning id into v_group_id;
  insert into public.player_group_members (group_id, user_id, nickname, level)
  values (v_group_id, v_user_id, btrim(p_nickname), p_level);

  loop
    v_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
    begin
      insert into public.player_group_invites (group_id, code, created_by, expires_at)
      values (v_group_id, v_code, v_user_id, v_expiration);
      exit;
    exception when unique_violation then
      null;
    end;
  end loop;

  return jsonb_build_object(
    'group', public.player_group_state(v_group_id),
    'invite_code', v_code,
    'expires_at', v_expiration
  );
end;
$$;

create or replace function public.create_player_group_invite()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_member_count integer;
  v_code text;
  v_expiration timestamptz := now() + interval '15 minutes';
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы создать приглашение.'; end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id for update;
  if v_group_id is null then raise exception 'Сначала создай группу.'; end if;
  select count(*) into v_member_count
  from public.player_group_members where group_id = v_group_id;
  if v_member_count <> 1 then raise exception 'В группе уже два игрока.'; end if;

  loop
    v_code := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
    begin
      insert into public.player_group_invites (group_id, code, created_by, expires_at, used_at)
      values (v_group_id, v_code, v_user_id, v_expiration, null)
      on conflict (group_id) do update
        set code = excluded.code, created_by = excluded.created_by,
            expires_at = excluded.expires_at, used_at = null;
      exit;
    exception when unique_violation then
      null;
    end;
  end loop;

  return jsonb_build_object('invite_code', v_code, 'expires_at', v_expiration);
end;
$$;

create or replace function public.accept_player_group_invite(p_code text, p_nickname text, p_level integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_owner_id uuid;
  v_owner_level integer;
  v_member_count integer;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы принять приглашение.'; end if;
  if p_level is null or p_level not between 1 and 10000 then raise exception 'Уровень игрока недопустим.'; end if;
  if p_nickname is null or length(btrim(p_nickname)) not between 1 and 24 then raise exception 'Ник должен содержать от 1 до 24 символов.'; end if;
  if p_code is null or upper(btrim(p_code)) !~ '^[A-F0-9]{8}$' then raise exception 'Код приглашения должен содержать 8 символов от 0 до 9 или A–F.'; end if;
  if exists (select 1 from public.player_group_members where user_id = v_user_id) then
    raise exception 'Ты уже состоишь в группе.';
  end if;

  select invite.group_id into v_group_id
  from public.player_group_invites as invite
  where invite.code = upper(btrim(p_code))
    and invite.used_at is null and invite.expires_at > now()
  for update;
  if v_group_id is null then raise exception 'Код приглашения недействителен или истёк.'; end if;

  perform 1 from public.player_groups where id = v_group_id for update;
  select count(*), min(level)
  into v_member_count, v_owner_level
  from public.player_group_members where group_id = v_group_id;
  select user_id into v_owner_id
  from public.player_group_members where group_id = v_group_id limit 1;
  if v_member_count <> 1 then raise exception 'В группе больше нет свободного места.'; end if;
  if v_owner_id = v_user_id then raise exception 'Нельзя пригласить самого себя.'; end if;
  if greatest(v_owner_level, p_level)::numeric / least(v_owner_level, p_level) >= 2 then
    raise exception 'Уровни игроков должны отличаться менее чем в 2 раза.';
  end if;

  insert into public.player_group_members (group_id, user_id, nickname, level)
  values (v_group_id, v_user_id, btrim(p_nickname), p_level);
  update public.player_group_invites set used_at = now() where group_id = v_group_id;
  return public.player_group_state(v_group_id);
end;
$$;

