create or replace function public.heartbeat_player_group(p_nickname text, p_level integer, p_in_dungeon boolean)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_min_level integer;
  v_max_level integer;
  v_invite jsonb;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы обновить статус группы.'; end if;
  if p_level is null or p_level not between 1 and 10000 then raise exception 'Уровень игрока недопустим.'; end if;
  if p_nickname is null or length(btrim(p_nickname)) not between 1 and 24 then raise exception 'Ник должен содержать от 1 до 24 символов.'; end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id for update;
  if v_group_id is null then return jsonb_build_object('group', null, 'dissolved', false); end if;

  update public.player_group_members
  set nickname = btrim(p_nickname), level = p_level,
      in_dungeon = coalesce(p_in_dungeon, false), heartbeat_at = now()
  where group_id = v_group_id and user_id = v_user_id;

  select min(level), max(level) into v_min_level, v_max_level
  from public.player_group_members where group_id = v_group_id;
  if v_min_level is not null and v_max_level::numeric / v_min_level >= 3 then
    delete from public.player_groups where id = v_group_id;
    return jsonb_build_object('group', null, 'dissolved', true);
  end if;
  select jsonb_build_object('invite_code', code, 'expires_at', expires_at)
  into v_invite
  from public.player_group_invites
  where group_id = v_group_id and created_by = v_user_id
    and used_at is null and expires_at > now();
  return jsonb_build_object(
    'group', public.player_group_state(v_group_id),
    'invite', v_invite,
    'dissolved', false
  );
end;
$$;

create or replace function public.share_player_group_reward(p_kind text, p_amount integer, p_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_recipient_id uuid;
  v_min_level integer;
  v_max_level integer;
  v_member_count integer;
  v_rows_inserted integer;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы поделиться добычей.'; end if;
  if p_kind is null or p_kind not in ('gold', 'essence') or p_amount is null or p_amount not between 1 and 100000 or p_request_id is null then
    raise exception 'Награда для передачи недопустима.';
  end if;
  if exists (
    select 1 from public.player_group_reward_receipts
    where sender_id = v_user_id and request_id = p_request_id
  ) then
    return jsonb_build_object('shared', true);
  end if;
  select group_id into v_group_id
  from public.player_group_members
  where user_id = v_user_id and in_dungeon and heartbeat_at > now() - interval '75 seconds';
  if v_group_id is null then return jsonb_build_object('shared', false); end if;

  select count(*), min(level), max(level)
  into v_member_count, v_min_level, v_max_level
  from public.player_group_members
  where group_id = v_group_id and in_dungeon and heartbeat_at > now() - interval '75 seconds';
  if v_member_count <> 2 or v_max_level::numeric / v_min_level >= 2 then
    return jsonb_build_object('shared', false);
  end if;
  select user_id into v_recipient_id
  from public.player_group_members where group_id = v_group_id and user_id <> v_user_id;
  insert into public.player_group_reward_receipts (group_id, sender_id, request_id)
  values (v_group_id, v_user_id, p_request_id)
  on conflict (sender_id, request_id) do nothing;
  get diagnostics v_rows_inserted = row_count;
  if v_rows_inserted = 0 then return jsonb_build_object('shared', true); end if;
  insert into public.player_group_inbox (group_id, recipient_id, sender_id, request_id, kind, amount)
  values (v_group_id, v_recipient_id, v_user_id, p_request_id, p_kind, p_amount);
  return jsonb_build_object('shared', true);
end;
$$;

create or replace function public.send_player_group_hint(p_kind text, p_floor integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_recipient_id uuid;
  v_member_count integer;
  v_min_level integer;
  v_max_level integer;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы отправить подсказку.'; end if;
  if p_kind is null or p_kind not in ('hint_secret', 'hint_rare') or p_floor is null or p_floor not between 1 and 1000000 then
    raise exception 'Подсказка недопустима.';
  end if;
  select group_id into v_group_id
  from public.player_group_members
  where user_id = v_user_id and in_dungeon and heartbeat_at > now() - interval '75 seconds';
  if v_group_id is null then return jsonb_build_object('sent', false); end if;
  select count(*), min(level), max(level)
  into v_member_count, v_min_level, v_max_level
  from public.player_group_members
  where group_id = v_group_id and in_dungeon and heartbeat_at > now() - interval '75 seconds';
  if v_member_count <> 2 or v_max_level::numeric / v_min_level >= 2 then
    return jsonb_build_object('sent', false);
  end if;
  select user_id into v_recipient_id
  from public.player_group_members where group_id = v_group_id and user_id <> v_user_id;
  insert into public.player_group_inbox (group_id, recipient_id, kind, floor)
  values (v_group_id, v_recipient_id, p_kind, p_floor);
  return jsonb_build_object('sent', true);
end;
$$;

create or replace function public.consume_player_group_inbox()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_updates jsonb;
begin
  if v_user_id is null or not exists (
    select 1 from public.player_group_members
    where user_id = v_user_id and in_dungeon and heartbeat_at > now() - interval '75 seconds'
  ) then
    return '[]'::jsonb;
  end if;

  with claimed as (
    delete from public.player_group_inbox where recipient_id = v_user_id
    returning kind, amount, floor, created_at
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'kind', kind, 'amount', amount, 'floor', floor, 'created_at', created_at
  )), '[]'::jsonb)
  into v_updates from claimed;
  return v_updates;
end;
$$;

