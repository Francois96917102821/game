    insert into public.player_group_battle_players (
      battle_id, user_id, hp, max_hp, potions, attack, defense, focus, heavy_multiplier
    )
    values (v_battle_id, v_user_id, v_hp, v_max_hp, v_potions, v_attack, v_defense, v_focus, v_heavy_multiplier)
    on conflict (battle_id, user_id) do nothing;

    select count(*) into v_member_count
    from public.player_group_battle_players where battle_id = v_battle_id;
    if v_member_count = 2 then
      update public.player_group_battles set status = 'active', updated_at = now()
      where id = v_battle_id and status = 'waiting';
    end if;
  end if;
  return public.player_group_battle_snapshot(v_battle_id);
end;
