create or replace function public.player_group_battle_action(
  p_battle_id uuid,
  p_action text,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_status text;
  v_round integer;
  v_boss_hp integer;
  v_boss_damage integer;
  v_player public.player_group_battle_players%rowtype;
  v_target public.player_group_battle_players%rowtype;
  v_damage integer := 0;
  v_healing integer := 0;
  v_raw_damage integer := 0;
  v_target_damage integer := 0;
  v_acted integer;
  v_response jsonb;
  v_log_item jsonb;
begin
  if v_user_id is null or p_battle_id is null or p_request_id is null or p_action is null or
    p_action not in ('attack', 'heavy', 'potion', 'guard') then
    raise exception 'Действие совместного боя недопустимо.';
  end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id;
  if v_group_id is null then raise exception 'Ты не состоишь в группе.'; end if;
  if not exists (
    select 1 from public.player_group_battles
    where id = p_battle_id and group_id = v_group_id
  ) then raise exception 'Совместный бой недоступен для этой группы.'; end if;

  select response into v_response
  from public.player_group_battle_action_receipts
  where battle_id = p_battle_id and user_id = v_user_id and request_id = p_request_id;
  if found then return v_response; end if;

  select status, round, boss_hp, boss_damage
  into v_status, v_round, v_boss_hp, v_boss_damage
  from public.player_group_battles where id = p_battle_id for update;
  select response into v_response
  from public.player_group_battle_action_receipts
  where battle_id = p_battle_id and user_id = v_user_id and request_id = p_request_id;
  if found then return v_response; end if;
  if v_status <> 'active' then raise exception 'Совместный бой сейчас не принимает действия.'; end if;
  select * into v_player
  from public.player_group_battle_players
  where battle_id = p_battle_id and user_id = v_user_id
  for update;
  if not found then raise exception 'Ты не участвуешь в этом бою.'; end if;
  if v_player.acted then raise exception 'Ты уже сделал ход в этом раунде; дождись ответа стража.'; end if;

  if p_action = 'attack' then
    v_damage := v_player.attack + floor(random() * 4)::integer;
    v_damage := least(v_damage, v_boss_hp);
    update public.player_group_battles set boss_hp = greatest(0, boss_hp - v_damage),
      updated_at = now() where id = p_battle_id;
    v_log_item := jsonb_build_object('round', v_round, 'type', 'player', 'user_id', v_user_id,
      'action', 'attack', 'damage', v_damage, 'text', 'нанёс урон стражу');
  elsif p_action = 'heavy' then
    if v_player.focus < 2 then raise exception 'Для сокрушительного удара нужно 2 запаса силы.'; end if;
    v_damage := floor(v_player.attack * v_player.heavy_multiplier)::integer;
    v_damage := least(v_damage, v_boss_hp);
    if v_damage <= 0 then raise exception 'Страж уже повержен.'; end if;
    update public.player_group_battles set boss_hp = greatest(0, boss_hp - v_damage),
      updated_at = now() where id = p_battle_id;
    v_log_item := jsonb_build_object('round', v_round, 'type', 'player', 'user_id', v_user_id,
      'action', 'heavy', 'damage', v_damage, 'text', 'нанёс сокрушительный удар');
  elsif p_action = 'potion' then
    if v_player.potions <= 0 or v_player.hp >= v_player.max_hp then
      raise exception 'Зелье сейчас нельзя использовать.';
    end if;
    v_healing := least(14, v_player.max_hp - v_player.hp);
    update public.player_group_battle_players
    set hp = hp + v_healing, potions = potions - 1
    where battle_id = p_battle_id and user_id = v_user_id;
    v_log_item := jsonb_build_object('round', v_round, 'type', 'player', 'user_id', v_user_id,
      'action', 'potion', 'healing', v_healing, 'text', 'выпил зелье');
  else
    update public.player_group_battle_players
    set guarding = true
    where battle_id = p_battle_id and user_id = v_user_id;
    v_log_item := jsonb_build_object('round', v_round, 'type', 'player', 'user_id', v_user_id,
      'action', 'guard', 'damage', 0, 'text', 'встал в защиту');
  end if;

  if p_action in ('attack', 'guard') then
    update public.player_group_battle_players
    set focus = least(3, focus + 1)
    where battle_id = p_battle_id and user_id = v_user_id;
  elsif p_action = 'heavy' then
    update public.player_group_battle_players
    set focus = focus - 2
    where battle_id = p_battle_id and user_id = v_user_id;
  end if;
  update public.player_group_battle_players
  set acted = true
  where battle_id = p_battle_id and user_id = v_user_id;
  update public.player_group_battles
  set action_log = action_log || jsonb_build_array(v_log_item), updated_at = now()
  where id = p_battle_id;

  if v_boss_hp - v_damage <= 0 then
    update public.player_group_battles set status = 'victory', boss_hp = 0, updated_at = now()
    where id = p_battle_id;
    v_log_item := jsonb_build_object('round', v_round, 'type', 'system', 'text', 'Страж повержен!');
    update public.player_group_battles set action_log = action_log || jsonb_build_array(v_log_item)
    where id = p_battle_id;
  elsif (select count(*) from public.player_group_battle_players
    where battle_id = p_battle_id and acted) = 2 then
    select * into v_target
    from public.player_group_battle_players
    where battle_id = p_battle_id and hp > 0
    order by random()
    limit 1
    for update;
    if not found then
      update public.player_group_battles set status = 'defeat', updated_at = now()
      where id = p_battle_id;
    else
      v_raw_damage := greatest(1, v_boss_damage - 2) + floor(random() *
        (v_boss_damage - greatest(1, v_boss_damage - 2) + 1))::integer;
      v_target_damage := greatest(1, v_raw_damage - v_target.defense);
      if v_target.guarding then v_target_damage := greatest(1, ceil(v_target_damage * 0.4)::integer); end if;
      update public.player_group_battle_players
      set hp = greatest(0, hp - v_target_damage)
      where battle_id = p_battle_id and user_id = v_target.user_id;
      v_log_item := jsonb_build_object('round', v_round, 'type', 'boss', 'target_id', v_target.user_id,
        'damage', least(v_target_damage, v_target.hp), 'text', 'Страж атаковал игрока');
      update public.player_group_battles
      set action_log = action_log || jsonb_build_array(v_log_item), updated_at = now(),
        status = case when v_target.hp <= v_target_damage then 'defeat' else status end,
        round = case when v_target.hp <= v_target_damage then round else round + 1 end
      where id = p_battle_id;
      if v_target.hp > v_target_damage then
        update public.player_group_battle_players
        set acted = false, guarding = false
        where battle_id = p_battle_id;
      end if;
    end if;
  end if;

  v_response := public.player_group_battle_snapshot(p_battle_id);
  insert into public.player_group_battle_action_receipts (battle_id, user_id, request_id, response)
  values (p_battle_id, v_user_id, p_request_id, v_response)
  on conflict (battle_id, user_id, request_id) do nothing;
  return v_response;
end;
$$;

create or replace function public.leave_player_group_battle(p_battle_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_group_id uuid;
  v_status text;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт, чтобы выйти из совместного боя.'; end if;
  select group_id into v_group_id
  from public.player_group_members where user_id = v_user_id;
  if v_group_id is null then raise exception 'Ты не состоишь в группе.'; end if;
  update public.player_group_battles
  set status = 'abandoned',
      action_log = action_log || jsonb_build_array(jsonb_build_object(
        'type', 'system', 'user_id', v_user_id, 'text', 'Игрок покинул бой.'
      )),
      updated_at = now()
  where id = p_battle_id and group_id = v_group_id and status in ('waiting', 'active')
  returning status into v_status;
  if not found then raise exception 'Совместный бой уже завершён или недоступен.'; end if;
  return public.player_group_battle_snapshot(p_battle_id);
end;
$$;

create or replace function public.player_mailbox_send(
  p_recipient_id uuid,
  p_request_id uuid,
  p_gear jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_sender_id uuid := (select auth.uid());
  v_group_id uuid;
  v_sender_nickname text;
  v_gear jsonb;
  v_existing public.player_mailbox_escrow%rowtype;
  v_mail_id uuid;
  v_request_key bigint;
  v_gear_key bigint;
  v_pair_key bigint;
begin
  if v_sender_id is null then raise exception 'Войди в аккаунт, чтобы отправить предмет.'; end if;
  if p_recipient_id is null or p_recipient_id = v_sender_id or p_request_id is null then
    raise exception 'Получатель или ключ отправки недопустим.';
  end if;
  if p_gear is null or jsonb_typeof(p_gear) <> 'object' or
    coalesce(p_gear ->> 'id', '') !~ '^gear-[0-9]+$' or
    coalesce(p_gear ->> 'type', '') not in ('weapon', 'armor') or
    coalesce(p_gear ->> 'name', '') = '' or length(p_gear ->> 'name') > 60 or
    coalesce(p_gear ->> 'bonus', '') !~ '^[1-9]$|^10$' then
    raise exception 'Можно отправить только корректную экипировку.';
  end if;
  v_gear := jsonb_build_object(
    'id', p_gear ->> 'id',
    'type', p_gear ->> 'type',
    'name', p_gear ->> 'name',
    'bonus', (p_gear ->> 'bonus')::integer
  );

  v_request_key := pg_catalog.hashtextextended(
    v_sender_id::text || ':mail-request:' || p_request_id::text, 0
  );
  v_gear_key := pg_catalog.hashtextextended(
    v_sender_id::text || ':mail-gear:' || (v_gear ->> 'id'), 0
  );
  v_pair_key := pg_catalog.hashtextextended(
    least(v_sender_id::text, p_recipient_id::text) || ':mail-pair:' ||
      greatest(v_sender_id::text, p_recipient_id::text), 0
  );
  perform pg_catalog.pg_advisory_xact_lock(v_request_key);
  perform pg_catalog.pg_advisory_xact_lock(v_gear_key);
  perform pg_catalog.pg_advisory_xact_lock(v_pair_key);

  select * into v_existing
  from public.player_mailbox_escrow
  where sender_id = v_sender_id and request_id = p_request_id
  for update;
  if found then
    if v_existing.source_gear_id <> (v_gear ->> 'id') or
      v_existing.recipient_id <> p_recipient_id or v_existing.gear <> v_gear then
      raise exception 'Этот предмет уже связан с другой отправкой.';
    end if;
    return jsonb_build_object('id', v_existing.id, 'status', v_existing.status);
  end if;

  select * into v_existing
  from public.player_mailbox_escrow
  where sender_id = v_sender_id and source_gear_id = (v_gear ->> 'id')
  for update;
  if found then
    if v_existing.recipient_id <> p_recipient_id or v_existing.gear <> v_gear then
      raise exception 'Этот предмет уже связан с другой отправкой.';
    end if;
    return jsonb_build_object('id', v_existing.id, 'status', v_existing.status);
  end if;

  select sender.group_id, sender.nickname into v_group_id, v_sender_nickname
  from public.player_group_members sender
  join public.player_group_members recipient on recipient.group_id = sender.group_id
  where sender.user_id = v_sender_id and recipient.user_id = p_recipient_id
    and sender.heartbeat_at > now() - interval '75 seconds'
    and recipient.heartbeat_at > now() - interval '75 seconds'
  for update of sender, recipient;
  if v_group_id is null then
    raise exception 'Получатель должен быть участником той же группы с heartbeat не старше 75 секунд.';
  end if;

  if not exists (
    select 1 from public.game_saves s
    where s.user_id = v_sender_id
      and case
        when jsonb_typeof(s.save_data #> '{meta,homestead,homes}') = 'array'
        then exists (
          select 1
          from jsonb_array_elements(s.save_data #> '{meta,homestead,homes}') h
          where h ->> 'tier' = 'mansion'
        )
        else false
      end
  ) or not exists (
    select 1 from public.game_saves s
    where s.user_id = p_recipient_id
      and case
        when jsonb_typeof(s.save_data #> '{meta,homestead,homes}') = 'array'
        then exists (
          select 1
          from jsonb_array_elements(s.save_data #> '{meta,homestead,homes}') h
          where h ->> 'tier' = 'mansion'
        )
        else false
      end
  ) then
    raise exception 'Отправитель и получатель должны сохранить покупку особняка в облаке.';
  end if;

  insert into public.player_mailbox_escrow (
    request_id, group_id, sender_id, recipient_id, sender_nickname,
    source_gear_id, gear
  ) values (
    p_request_id, v_group_id, v_sender_id, p_recipient_id, v_sender_nickname,
    v_gear ->> 'id', v_gear
  ) returning id into v_mail_id;
  return jsonb_build_object('id', v_mail_id, 'status', 'sender_pending');
end;
$$;

create or replace function public.player_mailbox_sender_removed(p_mail_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_mail public.player_mailbox_escrow%rowtype;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  select * into v_mail from public.player_mailbox_escrow
  where id = p_mail_id and sender_id = v_user_id for update;
  if not found then raise exception 'Отправка не найдена.'; end if;
  if v_mail.status = 'sender_pending' then
    update public.player_mailbox_escrow
    set status = 'ready', sender_removed_at = now()
    where id = p_mail_id returning * into v_mail;
  end if;
  return jsonb_build_object('id', v_mail.id, 'status', v_mail.status);
end;
$$;

create or replace function public.player_mailbox_list()
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', mail.id,
      'status', mail.status,
      'sender_nickname', mail.sender_nickname,
      'gear', mail.gear,
      'created_at', mail.created_at
    ) order by mail.created_at, mail.id)
    from public.player_mailbox_escrow mail
    where mail.recipient_id = v_user_id and mail.status in ('ready', 'claimed', 'delivered')
  ), '[]'::jsonb);
end;
$$;

create or replace function public.player_mailbox_claim(p_mail_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_mail public.player_mailbox_escrow%rowtype;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  select * into v_mail from public.player_mailbox_escrow
  where id = p_mail_id and recipient_id = v_user_id for update;
  if not found or v_mail.status = 'sender_pending' then
    raise exception 'Письмо ещё не готово к получению.';
  end if;
  if v_mail.status = 'ready' then
    update public.player_mailbox_escrow
    set status = 'claimed', claimed_at = now()
    where id = p_mail_id returning * into v_mail;
  end if;
  return jsonb_build_object(
    'id', v_mail.id,
    'status', v_mail.status,
    'sender_nickname', v_mail.sender_nickname,
    'gear', v_mail.gear
  );
end;
$$;

create or replace function public.player_mailbox_ack_claim(p_mail_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_mail public.player_mailbox_escrow%rowtype;
begin
  if v_user_id is null then raise exception 'Войди в аккаунт.'; end if;
  select * into v_mail from public.player_mailbox_escrow
  where id = p_mail_id and recipient_id = v_user_id for update;
  if not found or v_mail.status not in ('claimed', 'delivered') then
    raise exception 'Сначала сохрани предмет в постоянном запасе.';
  end if;
  if v_mail.status = 'claimed' then
    update public.player_mailbox_escrow
    set status = 'delivered', delivered_at = now()
    where id = p_mail_id returning * into v_mail;
  end if;
  return jsonb_build_object('id', v_mail.id, 'acknowledged', true, 'status', v_mail.status);
end;
